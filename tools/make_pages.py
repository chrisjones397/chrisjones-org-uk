#!/usr/bin/env python3
"""
make_pages.py

Give every painting on the website its own page, e.g.
    chrisjones.org.uk/paintings/porthmadog/

The pages are built from index.html, so index.html stays the one place where
paintings are added, removed, reordered or retitled. Run this script again
after any such change and every painting page is rebuilt to match.

Usage (the virtual environment is not needed; plain python3 is fine):
    python3 scripts/make_pages.py /Library/WebServer/Documents/prd/sync --dry-run
    python3 scripts/make_pages.py /Library/WebServer/Documents/prd/sync
    python3 scripts/make_pages.py --name "Composition in Blue with Border"

Names: each painting's caption is its master name. Its page address and image
file names come from the caption by one fixed rule:
    lower case; accents removed (é -> e); "&" -> "and"; "#", commas, full
    stops and apostrophes dropped; spaces and hyphens -> single hyphens.
    "Composition in Blue with Border" -> composition-in-blue-with-border
    "Collaboration with Teo #1"       -> collaboration-with-teo-1
--name prints the name for a caption, so new image files can be named to
match. The script stops if a painting's image files don't match its caption.
Caption style: "#" before a number in a series ("Apple #1"); a year goes
last, after a comma ("Nighttime, Brussels, 2013").

What it does:
  * Reads each painting block in index.html: its images, caption and section.
  * Writes paintings/<name>/index.html for each one, with the same header as
    the main page, the painting large (click it for the full-size image),
    its caption, Previous / Next links, and the footer.
  * Adds link-preview tags, so a link sent in a message shows the painting.
  * Points each thumbnail on the main page at its painting page instead of
    straight at the image file. The full-size image path is kept in a
    data-full attribute on the same link, so the script can be run again.
  * Adds a small marked block of extras to index.html (and to every painting
    page): the outline is removed from the paintings but kept round the
    section headings. The block is replaced, never duplicated, on each run.
  * Keeps old page addresses working after a painting is renamed: each entry
    in REDIRECTS gets a small page that forwards to the new address.
  * Removes pages it made earlier for paintings no longer on the main page.
    It only ever deletes pages that carry its own marker comment.

--dry-run reports what would happen and changes nothing.
"""
import argparse
import html
import os
import re
import shutil
import sys
import unicodedata

SITE_URL = "https://chrisjones.org.uk"     # used for link previews
PAGES_DIR = "paintings"
MARKER = "<!-- Generated by make_pages.py. Edit index.html or the script, not this file. -->"

# ---------------------------------------------------------------------------
# Footer settings. Change these and run the script again.
