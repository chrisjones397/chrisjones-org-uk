# the full address never appears in the page file for spam bots to collect.
EMAIL_USER = "hello"
EMAIL_DOMAIN = "chrisjones.org.uk"
INSTAGRAM = "only1jones2"
COPYRIGHT = "&copy;2026 Christopher Jones"

