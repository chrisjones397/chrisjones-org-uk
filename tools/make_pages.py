def body_extras():
    return f"  {EXTRAS_START}\n  {EXTRAS_BODY}\n  {EXTRAS_END}\n" if EXTRAS_BODY else ""


def fail(msg):
    sys.exit(f"ERROR: {msg}")


def footer_html():
    lines = []
    if EMAIL_USER and EMAIL_DOMAIN:
        # Split into parts and reversed, so the address never appears whole.
        parts = list(reversed([EMAIL_USER, "@", EMAIL_DOMAIN]))
        js_parts = ", ".join("'" + p.replace("\\", "\\\\").replace("'", "\\'") + "'" for p in parts)
        lines.append(
            '<p class="footer-email" id="footer-email"></p>\n'
            '    <script>(function(){var p=[' + js_parts + '];'
            'document.getElementById("footer-email").textContent=p.reverse().join("");})();</script>')
    if INSTAGRAM:
        lines.append(f'<p><a href="https://www.instagram.com/{INSTAGRAM}/" '
                     f'aria-label="Instagram: {INSTAGRAM}" title="Instagram">{INSTAGRAM_ICON}</a></p>')
    if COPYRIGHT:
        lines.append(f"<p>{COPYRIGHT}</p>")
    if not lines:
        return ""
    return '\n  <footer class="site-footer">\n    ' + "\n    ".join(lines) + "\n  </footer>"


# A painting block on the main page: the link, the <picture>, then the caption.
BLOCK_RE = re.compile(
    r'<a href="(?P<href>[^"]+)"(?: data-full="(?P<full>[^"]+)")?>\s*'
    r'(?P<picture><picture>.*?</picture>)\s*</a>\s*'
    r'<p>(?P<caption>.*?)</p>',
    re.S)
SECTION_RE = re.compile(r'<h3 id="(?P<id>[^"]+)">(?P<title>.*?)</h3>', re.S)
EXTRAS_RE = re.compile(r"\s*" + re.escape(EXTRAS_START) + r".*?" + re.escape(EXTRAS_END), re.S)


def read_paintings(index_html):
    """Find every painting block, in page order, with the section it sits in."""
    sections = [(m.start(), m.group("id"), m.group("title"))
                for m in SECTION_RE.finditer(index_html)]
    paintings = []
    for m in BLOCK_RE.finditer(index_html):
        full = m.group("full") or m.group("href")
        if not full.startswith("img/"):
            fail(f"a painting link points at {full!r}, expected an image under img/")
        name = slug(m.group("caption"))
        if not name:
            fail(f"cannot make a name from the caption {m.group('caption')!r}")
        # every image file of this painting must be named after its caption
        for path in set(re.findall(r'(img/[^\s",]+)', m.group("picture"))) | {full}:
            stem = os.path.splitext(os.path.basename(path))[0]
            if not re.fullmatch(re.escape(name) + r"(-\d+|-full)?", stem):
                fail(f"the caption {plain(m.group('caption'))!r} needs its image files named "
                     f"{name}..., but index.html uses {path}")
        sec = [s for s in sections if s[0] < m.start()]
        section_id = sec[-1][1] if sec else "gallery"
        jpg = re.search(r'<img[^>]*\ssrc="([^"]+)"', m.group("picture"))
        big = re.findall(r'(img/jpg/[^\s",]+-(\d+)\.jpg)', m.group("picture"))
        big = [b for b in big if int(b[1]) <= 1024]
        preview = max(big, key=lambda t: int(t[1]))[0] if big else (jpg.group(1) if jpg else full)
        paintings.append(dict(
            name=name, full=full, caption=m.group("caption").strip(),
            picture=m.group("picture"), section=section_id, preview=preview,
            span=(m.start(), m.end())))
    if not paintings:
        fail("no painting blocks found in index.html")
    names = [p["name"] for p in paintings]
    dupes = {n for n in names if names.count(n) > 1}
    if dupes:
        fail(f"two paintings would get the same page name: {', '.join(sorted(dupes))}")
    return paintings


def slug(caption):
    """A caption's page and file name, by the fixed rule in the notes at the top."""
    t = unicodedata.normalize("NFKD", plain(caption))
    t = "".join(c for c in t if not unicodedata.combining(c)).lower()
    t = t.replace("&", " and ")
    t = re.sub(r"[#,.'\u2019]", "", t)
    return re.sub(r"[^a-z0-9]+", "-", t).strip("-")


def plain(text):
    """Caption as plain text, for the title and preview tags."""
    return html.unescape(re.sub(r"<[^>]+>", "", text)).replace("‑", "-").strip()


def page_picture(picture):
    """The main page's <picture>, adjusted for a page two folders down."""
    p = re.sub(r'(?<=["\s,])img/', "../../img/", picture)
    p = re.sub(r'sizes="[^"]*"', 'sizes="(max-width: 1240px) 100vw, 1200px"', p)
    p = re.sub(r'\s*loading="lazy"', "", p)
    return p


def page_header(header):
    """The main page's header, with its links pointing back to the main page."""
    h = header.replace('href="#"', 'href="../../"')
    h = re.sub(r'href="#([^"]+)"', r'href="../../#\1"', h)
    h = re.sub(r'data="(?!https?:|/|\.\./)([^"]+)"', r'data="../../\1"', h)
    h = re.sub(r'src="(?!https?:|/|\.\./)([^"]+)"', r'src="../../\1"', h)
    return h


def build_page(p, prev, nxt, head_bits, style, header):
    title = plain(p["caption"])
    esc = html.escape
    url = f"{SITE_URL}/{PAGES_DIR}/{p['name']}/"
    image = f"{SITE_URL}/{p['preview']}"
    prev_html = (f'<a href="../{prev["name"]}/" rel="prev">&larr; Previous</a>' if prev
                 else '<span aria-disabled="true">&larr; Previous</span>')
    next_html = (f'<a href="../{nxt["name"]}/" rel="next">Next &rarr;</a>' if nxt
                 else '<span aria-disabled="true">Next &rarr;</span>')
    return f"""<!DOCTYPE html>
{MARKER}
<html lang="en" data-page="painting">
<head>
{head_bits}
  <title>{esc(title)} - Christopher Jones - Fine Art</title>
  <meta name="description" content="{esc(title)}, by Christopher Jones.">
  <link rel="canonical" href="{url}">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="Christopher Jones - Fine Art">
  <meta property="og:title" content="{esc(title)}">
  <meta property="og:description" content="By Christopher Jones">
  <meta property="og:url" content="{url}">
  <meta property="og:image" content="{image}">
  <meta name="twitter:card" content="summary_large_image">
  <style>{style}{PAGE_CSS}  </style>
  {EXTRAS_START}
  {EXTRAS_HEAD}
  {EXTRAS_END}
</head>
<body>

{header}

  <main id="main-content">
    <article class="painting-page">
      <a class="full-size" href="../../{p["full"]}" title="Open the full-size image">
      {page_picture(p["picture"])}
      </a>
      <h1>{p["caption"]}</h1>
      <nav class="painting-links" aria-label="Previous and next paintings">
        {prev_html}
        {next_html}
      </nav>
    </article>
  </main>
{footer_html()}

{body_extras()}</body>
</html>
"""


def build_redirect(new):
    url = f"{SITE_URL}/{PAGES_DIR}/{new}/"
    return f"""<!DOCTYPE html>
{REDIRECT_MARKER}
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>Moved</title>
  <meta name="robots" content="noindex">
  <link rel="canonical" href="{url}">
  <meta http-equiv="refresh" content="0; url=../{new}/">
</head>
<body>
  <p>This painting has moved to <a href="../{new}/">{url}</a>.</p>
</body>
</html>
"""


def head_bits_from(index_html):
    """Charset, viewport, icons and fonts from the main page's <head>."""
    head = re.search(r"<head>(.*?)</head>", index_html, re.S)
    if not head:
        fail("no <head> found in index.html")
    keep = []
    for line in head.group(1).splitlines():
        s = line.strip()
        if s.startswith("<meta charset") or s.startswith('<meta name="viewport"'):
            keep.append(line)
        elif s.startswith("<link") and 'rel="preload"' not in s:
            keep.append(re.sub(r'href="(?!https?:|/|\.\./)([^"]+)"', r'href="../../\1"', line))
    return "\n".join(keep)


def add_extras(index_html):
    """Put the extras into index.html, replacing any earlier copy."""
    s = EXTRAS_RE.sub("", index_html)
    if "</head>" not in s or "</body>" not in s:
        fail("index.html has no </head> or </body>")
    s = s.replace("</head>", f"  {EXTRAS_START}\n  {EXTRAS_HEAD}\n  {EXTRAS_END}\n</head>", 1)
    if EXTRAS_BODY:
        i = s.rfind("</body>")
        s = s[:i] + f"  {EXTRAS_START}\n  {EXTRAS_BODY}\n  {EXTRAS_END}\n  " + s[i:]
    return s


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("site", nargs="?", help="the website folder, containing index.html")
    ap.add_argument("--name", metavar="CAPTION",
                    help="just print the page and file name for a caption, and stop")
    ap.add_argument("--dry-run", action="store_true",
                    help="report what would happen without changing anything")
    a = ap.parse_args()
    if a.name is not None:
        print(slug(a.name))
        return
    if not a.site:
        ap.error("give the website folder (or --name with a caption)")

    index_path = os.path.join(a.site, "index.html")
    if not os.path.isfile(index_path):
        fail(f"no index.html in {a.site}")
    if not os.path.isfile(os.path.join(a.site, "CNAME")):
        fail(f"{a.site} does not look like the website folder (no CNAME file)")
    with open(index_path, encoding="utf-8") as f:
        index_html = f.read()

    paintings = read_paintings(index_html)
    style = re.search(r"<style>(.*?)</style>", index_html, re.S)
    header = re.search(r'(  <header\b.*?</header>)', index_html, re.S)
    if not style or not header:
        fail("could not find the <style> and <header> in index.html")
    head_bits = head_bits_from(index_html)
    hdr = page_header(header.group(1))

    # Check every image the pages will use actually exists.
    missing = []
    for p in paintings:
        for path in set(re.findall(r'(img/[^\s",]+)', p["picture"])) | {p["full"]}:
            if not os.path.isfile(os.path.join(a.site, path)):
                missing.append(path)
    if missing:
        fail("these images are referenced in index.html but missing:\n  " +
             "\n  ".join(sorted(missing)))

    pages_root = os.path.join(a.site, PAGES_DIR)
    wanted = {p["name"] for p in paintings}
    print(f"Found {len(paintings)} paintings in index.html")
    for old, new in REDIRECTS.items():
        if old in wanted:
            fail(f"REDIRECTS forwards {old!r}, but a painting on the main page has that name")
        if new not in wanted:
            fail(f"REDIRECTS forwards {old!r} to {new!r}, which is not a painting on the main page")

    for i, p in enumerate(paintings):
        prev = paintings[i - 1] if i > 0 else None
        nxt = paintings[i + 1] if i + 1 < len(paintings) else None
        out_dir = os.path.join(pages_root, p["name"])
        page = build_page(p, prev, nxt, head_bits, style.group(1), hdr)
        path = os.path.join(out_dir, "index.html")
        old = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
        status = "new" if old is None else ("unchanged" if old == page else "updated")
        print(f"  {status:9s} {PAGES_DIR}/{p['name']}/")
        if not a.dry_run and status != "unchanged":
            os.makedirs(out_dir, exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(page)

    # Forwarding pages for old names.
    for old, new in sorted(REDIRECTS.items()):
        path = os.path.join(pages_root, old, "index.html")
        page = build_redirect(new)
        before = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
        if before is not None and before != page and MARKER not in before and REDIRECT_MARKER not in before:
            print(f"  left alone {PAGES_DIR}/{old}/  (not made by this script)")
            continue
        status = "new" if before is None else ("unchanged" if before == page else "updated")
        print(f"  {status:9s} {PAGES_DIR}/{old}/  (forwards to {new}/)")
        if not a.dry_run and status != "unchanged":
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(page)

    # Remove pages for paintings no longer on the main page (only ones we made).
    if os.path.isdir(pages_root):
        for d in sorted(os.listdir(pages_root)):
            page = os.path.join(pages_root, d, "index.html")
            if d in wanted or d in REDIRECTS or not os.path.isfile(page):
                continue
            with open(page, encoding="utf-8") as f:
                text = f.read()
                ours = MARKER in text or REDIRECT_MARKER in text
            if ours:
                print(f"  removed   {PAGES_DIR}/{d}/  (no longer on the main page)")
                if not a.dry_run:
                    shutil.rmtree(os.path.join(pages_root, d))
            else:
                print(f"  left alone {PAGES_DIR}/{d}/  (not made by this script)")

    # Point each thumbnail on the main page at its painting page.
    new_index, shift, changed = index_html, 0, 0
    for p in paintings:
        old_link = re.match(r'<a href="[^"]+"(?: data-full="[^"]+")?>',
                            index_html[p["span"][0]:]).group(0)
        new_link = f'<a href="{PAGES_DIR}/{p["name"]}/" data-full="{p["full"]}">'
        if old_link != new_link:
            s = p["span"][0] + shift
            new_index = new_index[:s] + new_link + new_index[s + len(old_link):]
            shift += len(new_link) - len(old_link)
            changed += 1
    new_index = add_extras(new_index)
    would = "would be " if a.dry_run else ""
    if changed:
        print(f"index.html: {changed} thumbnail links {would}pointed at their painting pages")
    if new_index != index_html:
        print(f"index.html: {would}updated")
        if not a.dry_run:
            with open(index_path, "w", encoding="utf-8") as f:
                f.write(new_index)
    else:
        print("index.html: unchanged")
    print("Dry run: nothing was changed." if a.dry_run else "Done.")


if __name__ == "__main__":
    main()
